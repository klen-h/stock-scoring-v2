# -*- coding: utf-8 -*-
"""
================================================================================
【文件作用】本地开发专用开关（**默认全部关闭**，生产环境不受影响）
================================================================================

## 为什么需要这个模块（2026-11-01，用户提问驱动）

用户："本地开发的时候，每次修改，前后端都会热更新，是不是也会消耗流量，能不能缓存下来，
我一般都是盘后开发，数据有差异没有关系。"

**会。而且这是"小流量偷跑"的主要机制之一**，代码里早有记录（见
`mainforce/flow.py` 的 `_FLOW_DISK_PATH` 注释：「本机 run.py --reload（改一次代码即重启）
+ 各式脚本 → 单日可冲到 68 次 ≈ 592MB」）。

机制：
  · 后端热更新 = 进程重启 ⇒ **模块级内存缓存全部清零**；
  · 本机 SQLite 缓存（`backend/data/*.db`）还在，但都有**版本/时效门控**：
      - `mainforce/flow.py::_disk_load` —— 要求 `sync_meta.version("mainflow")` 一致 **且** 12 小时内；
      - `research_cache.flow_map` —— 同样 24h 新鲜度判定。
  · 盘后开发时数据**本来就不再变**，但版本号可能因当天日批写入而变、或 TTL 已过
    ⇒ 门控判"陈旧" ⇒ **回源整表**。
  · 实测（`scripts/egress_probe.py`，11-01 23:02→23:14 窗口）：
    一次冷启动里 `SELECT ... FROM mainflow_history` 单条 **214,101 行 ≈ 23MB**。

## 这个开关做什么

`DEV_STALE_CACHE=1` ⇒ 门控判陈旧时**不再回源，直接复用本机缓存**，并打印一行醒目提示。

⚠️ 语义变化（必须知道）：
  · 拿到的是**可能落后若干小时到若干天**的资金流/行情数据；
  · 影响面：`flow5_amt`、chip 网格、闸门 `ready`、观察器降级判据等；
  · **只在本地开发有意义**（盘后数据本就不变，差异通常是"少了当天补写的那几行"）。

## 怎么用

在 `backend/.env` 里加一行（`backend/run.py` 会加载它）：

    DEV_STALE_CACHE=1

不需要时删掉即恢复严格门控。**绝不要在 Render/Actions 里配置它**。
================================================================================
"""

import os


def stale_cache_enabled() -> bool:
    """是否允许复用"门控判定为陈旧"的本机缓存（本地开发专用）。

    ★ **每次调用都读环境变量**（不在 import 时固化）——
      这样同一进程内也能用 monkeypatch / 测试临时开启，不必重启。
    """
    v = (os.environ.get("DEV_STALE_CACHE") or "").strip().lower()
    return v in ("1", "true", "yes", "on")
